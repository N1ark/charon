//! Reconstruct structured expressions from rustc's various constant representations.
use super::*;
use rustc_const_eval::const_eval;
use rustc_const_eval::interpret::{InterpResult, interp_ok};
use rustc_middle::mir::interpret;
use rustc_middle::{mir, ty};

impl ConstantLiteral {
    /// Rustc always represents string constants as `&[u8]`, but this
    /// is not nice to consume. This associated function interpret
    /// bytes as an unicode string, and as a byte string otherwise.
    fn byte_str(bytes: Vec<u8>) -> Self {
        match String::from_utf8(bytes.clone()) {
            Ok(s) => Self::Str(s),
            Err(_) => Self::ByteStr(bytes),
        }
    }
}

#[tracing::instrument(level = "trace", skip(s))]
pub(crate) fn scalar_int_to_constant_literal<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    x: rustc_middle::ty::ScalarInt,
    ty: rustc_middle::ty::Ty<'tcx>,
) -> ConstantLiteral {
    match ty.kind() {
        ty::Char => ConstantLiteral::Char(
            char::try_from(x).s_expect(s, "scalar_int_to_constant_literal: expected a char"),
        ),
        ty::Bool => ConstantLiteral::Bool(
            x.try_to_bool()
                .s_expect(s, "scalar_int_to_constant_literal: expected a bool"),
        ),
        ty::Int(kind) => {
            let v = x.to_int(x.size());
            ConstantLiteral::Int(ConstantInt::Int(v, kind.sinto(s)))
        }
        ty::Uint(kind) => {
            let v = x.to_uint(x.size());
            ConstantLiteral::Int(ConstantInt::Uint(v, kind.sinto(s)))
        }
        ty::Float(kind) => {
            let v = x.to_bits_unchecked();
            bits_and_type_to_float_constant_literal(v, kind.sinto(s))
        }
        _ => {
            let ty_sinto: Ty = ty.sinto(s);
            supposely_unreachable_fatal!(
                s,
                "scalar_int_to_constant_literal_ExpectedLiteralType";
                { ty, ty_sinto, x }
            )
        }
    }
}

/// Converts a bit-representation of a float of type `ty` to a constant literal
fn bits_and_type_to_float_constant_literal(bits: u128, ty: FloatTy) -> ConstantLiteral {
    use rustc_apfloat::{Float, ieee};
    let string = match &ty {
        FloatTy::F16 => ieee::Half::from_bits(bits).to_string(),
        FloatTy::F32 => ieee::Single::from_bits(bits).to_string(),
        FloatTy::F64 => ieee::Double::from_bits(bits).to_string(),
        FloatTy::F128 => ieee::Quad::from_bits(bits).to_string(),
    };
    ConstantLiteral::Float(string, ty)
}

impl ConstantExprKind {
    pub fn decorate(self, ty: Ty, _span: Span) -> Decorated<Self> {
        Decorated {
            contents: Box::new(self),
            ty,
        }
    }
}

/// Whether a `DefId` is a `AnonConst`. An anonymous constant is
/// generated by Rustc, hoisting every constat bits from items as
/// separate top-level items. This AnonConst mechanism is internal to
/// Rustc; we don't want to reflect that, instead we prefer inlining
/// those. `is_anon_const` is used to detect such AnonConst so that we
/// can evaluate and inline them.
pub(crate) fn is_anon_const(
    did: rustc_span::def_id::DefId,
    tcx: rustc_middle::ty::TyCtxt<'_>,
) -> bool {
    matches!(tcx.def_kind(did), rustc_hir::def::DefKind::AnonConst)
}

/// Evaluate a `ty::Const`.
pub fn eval_ty_constant<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    uv: rustc_middle::ty::AliasConst<'tcx>,
) -> Option<ty::Const<'tcx>> {
    use ty::TypeVisitableExt;
    let tcx = s.base().tcx;
    let typing_env = s.typing_env();
    if uv.has_non_region_param() {
        return None;
    }
    let def = uv.kind.opt_def_id().unwrap();
    let span = tcx.def_span(def);
    let erased_uv = tcx.erase_and_anonymize_regions(uv);
    let val = tcx
        .const_eval_resolve_for_typeck(typing_env, erased_uv, span)
        .ok()?
        .ok()?;
    let ty = tcx.type_of(def).instantiate(tcx, uv.args);
    let ty = normalize(tcx, typing_env, ty);
    Some(ty::Const::new_value(tcx, val, ty))
}

/// Evaluate a constant (or one of its promoteds) to an allocation and read it back. Unlike
/// valtrees, this keeps track of the allocations the value points to.
pub fn eval_constant_to_alloc<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    def_id: rustc_span::def_id::DefId,
    args: ty::GenericArgsRef<'tcx>,
    promoted: Option<mir::Promoted>,
) -> Option<ConstantExpr> {
    use ty::TypeVisitableExt;
    let tcx = s.base().tcx;
    if args.has_non_region_param() {
        return None;
    }
    let instance = ty::Instance::try_resolve(tcx, s.typing_env(), def_id, args).ok()??;
    let cid = interpret::GlobalId { instance, promoted };
    let alloc = tcx
        .eval_to_allocation_raw(s.typing_env().as_query_input(cid))
        .ok()?;
    let val = mir::ConstValue::Indirect {
        alloc_id: alloc.alloc_id,
        offset: rustc_abi::Size::ZERO,
    };
    const_value_to_constant_expr(s, alloc.ty, val, tcx.def_span(def_id)).discard_err()
}

impl<'tcx, S: UnderOwnerState<'tcx>> SInto<S, ConstantExpr> for ty::Const<'tcx> {
    #[tracing::instrument(level = "trace", skip(s))]
    fn sinto(&self, s: &S) -> ConstantExpr {
        let tcx = s.base().tcx;
        let span = rustc_span::DUMMY_SP;
        match self.kind() {
            ty::ConstKind::Param(p) => {
                let ty = p.find_const_ty_from_env(s.param_env());
                let kind = ConstantExprKind::ConstRef { id: p.sinto(s) };
                kind.decorate(ty.sinto(s), span.sinto(s))
            }
            ty::ConstKind::Infer(..) => {
                fatal!(s[span], "ty::ConstKind::Infer node? {:#?}", self)
            }

            ty::ConstKind::Alias(_, ucv) => {
                let def = ucv
                    .kind
                    .opt_def_id()
                    .expect("AliasConstKind with no def id?");
                let inline = s.base().options.inline_anon_consts && is_anon_const(def, tcx);
                if inline
                    && s.base().options.anon_allocs_as_globals
                    && let Some(val) = eval_constant_to_alloc(s, def, ucv.args, None)
                {
                    val
                } else if inline && let Some(val) = eval_ty_constant(s, ucv) {
                    val.sinto(s)
                } else {
                    use rustc_middle::query::QueryKey;
                    let span = tcx
                        .def_ident_span(def)
                        .unwrap_or_else(|| def.default_span(tcx));
                    let item = translate_item_ref(s, def, ucv.args);
                    let kind = ConstantExprKind::NamedGlobal(item);
                    let ty = tcx.type_of(def).instantiate(tcx, ucv.args);
                    let ty = normalize(tcx, s.typing_env(), ty);
                    kind.decorate(ty.sinto(s), span.sinto(s))
                }
            }

            ty::ConstKind::Value(val) => valtree_to_constant_expr(s, val.valtree, val.ty, span),
            ty::ConstKind::Error(_) => fatal!(s[span], "ty::ConstKind::Error"),
            ty::ConstKind::Expr(e) => fatal!(s[span], "ty::ConstKind::Expr {:#?}", e),

            ty::ConstKind::Bound(i, bound) => {
                supposely_unreachable_fatal!(s[span], "ty::ConstKind::Bound"; {i, bound})
            }
            _ => fatal!(s[span], "unexpected case"),
        }
    }
}

impl<'tcx, S: UnderOwnerState<'tcx>> SInto<S, ConstantExpr> for ty::Value<'tcx> {
    #[tracing::instrument(level = "trace", skip(s))]
    fn sinto(&self, s: &S) -> ConstantExpr {
        valtree_to_constant_expr(s, self.valtree, self.ty, rustc_span::DUMMY_SP)
    }
}

#[tracing::instrument(level = "trace", skip(s))]
pub(crate) fn valtree_to_constant_expr<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    valtree: rustc_middle::ty::ValTree<'tcx>,
    ty: rustc_middle::ty::Ty<'tcx>,
    span: rustc_span::Span,
) -> ConstantExpr {
    let tcx = s.base().tcx;
    let mut ty = normalize(tcx, s.typing_env(), ty::Unnormalized::new_wip(ty));

    // Reveal opaque types.
    if let ty::Alias(_, alias) = ty.kind()
        && let ty::AliasTyKind::Opaque { def_id } = alias.kind
    {
        let hidden_ty = tcx.type_of(def_id).instantiate(tcx, alias.args);
        ty = normalize(tcx, s.typing_env(), hidden_ty);
    }

    let kind = match (&*valtree, ty.kind()) {
        (_, ty::Pat(inner_ty, _)) => {
            return valtree_to_constant_expr(s, valtree, *inner_ty, span);
        }
        (ty::ValTreeKind::Branch(fields), ty::Ref(_, inner_ty, _))
            if let ty::Slice(_) | ty::Str = inner_ty.kind() =>
        {
            let len = fields.len() as u64;
            let pointee_ty = match inner_ty.kind() {
                ty::Slice(elem) => ty::Ty::new_array(tcx, *elem, len),
                ty::Str if s.base().options.unsized_strings => {
                    ty::Ty::new_array(tcx, tcx.types.u8, len)
                }
                ty::Str => *inner_ty,
                _ => unreachable!(),
            };
            let val = valtree_to_constant_expr(s, valtree, pointee_ty, span);
            let len = ty::Const::from_target_usize(tcx, len).sinto(s);
            ConstantExprKind::Borrow(val, vec![], Some(UnsizingMetadata::Length(len)))
        }
        // For other unsized pointees, computing the metadata requires putting them in an allocation.
        (_, ty::Ref(_, inner_ty, _)) if !inner_ty.is_sized(tcx, s.typing_env()) => {
            let val = tcx.valtree_to_const_val(ty::Value { ty, valtree });
            match const_value_to_constant_expr(s, ty, val, span).discard_err() {
                Some(expr) => return expr,
                None => fatal!(s[span], "Couldn't read an unsized constant"; {valtree, ty}),
            }
        }
        (_, ty::Ref(_, inner_ty, _)) => {
            let val = valtree_to_constant_expr(s, valtree, *inner_ty, span);
            ConstantExprKind::Borrow(val, vec![], None)
        }
        (ty::ValTreeKind::Branch(valtrees), ty::Str) => {
            let bytes = valtrees
                .iter()
                .map(|x| match x.try_to_leaf() {
                    Some(leaf) => leaf.to_u8(),
                    None => fatal!(
                        s[span],
                        "Expected a flat list of leaves while translating \
                            a str literal, got a arbitrary valtree."
                    ),
                })
                .collect();
            ConstantExprKind::Literal(ConstantLiteral::byte_str(bytes))
        }
        (ty::ValTreeKind::Branch(fields), ty::Array(..) | ty::Slice(..) | ty::Tuple(..)) => {
            let fields = fields.iter().map(|field| field.sinto(s)).collect();
            match ty.kind() {
                ty::Array(..) | ty::Slice(..) => ConstantExprKind::Array { fields },
                ty::Tuple(_) => ConstantExprKind::Tuple { fields },
                _ => unreachable!(),
            }
        }
        (ty::ValTreeKind::Branch(_), ty::Adt(def, _)) => {
            let contents: rustc_middle::ty::DestructuredAdtConst =
                ty::Value { valtree, ty }.destructure_adt_const();

            let fields = contents.fields.iter().copied();
            let variant_idx = contents.variant;
            let variant_def = &def.variant(variant_idx);

            ConstantExprKind::Adt {
                kind: get_variant_kind(def, variant_idx, s),
                fields: fields
                    .into_iter()
                    .zip(&variant_def.fields)
                    .map(|(value, field)| ConstantFieldExpr {
                        field: field.did.sinto(s),
                        value: value.sinto(s),
                    })
                    .collect(),
            }
        }
        (ty::ValTreeKind::Branch(fields), ty::FnDef(def_id, args)) if fields.is_empty() => {
            // Note: loss of precision, we erase the bound vars.
            let args = erase_free_regions(s.base().tcx, args.skip_binder());
            ConstantExprKind::FnDef(translate_item_ref(s, *def_id, args))
        }
        (ty::ValTreeKind::Leaf(x), ty::RawPtr(_, _)) => {
            let raw_address = x.to_bits_unchecked();
            ConstantExprKind::Literal(ConstantLiteral::PtrNoProvenance(raw_address))
        }
        (ty::ValTreeKind::Leaf(x), _) => {
            ConstantExprKind::Literal(scalar_int_to_constant_literal(s, *x, ty))
        }
        _ => supposely_unreachable_fatal!(
            s[span], "valtree_to_expr";
            {valtree, ty}
        ),
    };
    kind.decorate(ty.sinto(s), span.sinto(s))
}

/// The provenance to give to the bytes of a pointer into the given allocation.
fn alloc_provenance<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    alloc_id: interpret::AllocId,
) -> ConstantByteProvenance {
    use interpret::GlobalAlloc::*;
    match s.base().tcx.global_alloc(alloc_id) {
        Function { instance } => match instance.def {
            // A stateless closure coerced to a fn pointer. Needs special handling, since the
            // shim has no DefId.
            ty::InstanceKind::Shim(ty::ShimKind::ClosureOnce { .. }) => {
                let ty::TyKind::Closure(def_id, args) = instance.args.type_at(0).kind() else {
                    unreachable!("ClosureOnce shim on non-closure")
                };
                ConstantByteProvenance::ClosureAsFn(ClosureArgs::sfrom(s, *def_id, args))
            }
            _ => ConstantByteProvenance::Function(translate_item_ref(
                s,
                instance.def_id(),
                instance.args,
            )),
        },
        Static(..) | Memory(..) => match alloc_as_global(s, alloc_id) {
            Some(item) => ConstantByteProvenance::Global(item),
            None => ConstantByteProvenance::Unknown,
        },
        // The vtable of a `dyn` pointer.
        VTable(ty, preds) if preds.principal().is_some() => {
            let tcx = s.base().tcx;
            let dyn_ty = ty::Ty::new_dynamic(tcx, preds, tcx.lifetimes.re_erased);
            let ptr_ty = |ty| ty::Ty::new_imm_ptr(tcx, ty);
            match compute_unsizing_metadata(s, ptr_ty(ty), ptr_ty(dyn_ty)) {
                UnsizingMetadata::DirectVTable(proof) => ConstantByteProvenance::VTable(proof),
                _ => ConstantByteProvenance::Unknown,
            }
        }
        // TODO: TypeIds
        TypeId { .. } | VTable(..) => ConstantByteProvenance::Unknown,
    }
}

/// The global that an allocation corresponds to, if any.
fn alloc_as_global<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    alloc_id: interpret::AllocId,
) -> Option<ItemRef> {
    use interpret::GlobalAlloc::*;
    let tcx = s.base().tcx;
    match tcx.global_alloc(alloc_id) {
        // TODO: nested statics are synthetic items that make the rest of the machinery ICE, so we
        // don't turn them into named globals yet.
        Static(did)
            if let rustc_hir::def::DefKind::Static { nested: false, .. } = tcx.def_kind(did) =>
        {
            Some(translate_item_ref(s, did, Default::default()))
        }
        Memory(_) if s.base().options.anon_allocs_as_globals => {
            let def_id = DefId::make_anon_alloc(s, alloc_id);
            Some(ItemRef::dummy_without_generics(s, def_id))
        }
        _ => None,
    }
}

/// Read the raw bytes of an evaluated operand, keeping track of uninitialized bytes and pointer
/// provenance. Used for values that have no structured representation (e.g. unions).
fn op_to_raw_bytes<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    op: &rustc_const_eval::interpret::OpTy<'tcx>,
) -> InterpResult<'tcx, Vec<ConstantByte>> {
    op.as_mplace_or_imm().either(
        |mplace| mplace_to_raw_bytes(s, ecx, &mplace),
        |imm| interp_ok(imm_to_raw_bytes(s, &imm)),
    )
}

/// The bytes of an immediate, which is made of at most two scalars.
fn imm_to_raw_bytes<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    imm: &rustc_const_eval::interpret::ImmTy<'tcx>,
) -> Vec<ConstantByte> {
    use rustc_abi::Size;
    use rustc_const_eval::interpret::Immediate;
    let mut bytes = vec![ConstantByte::Uninit; imm.layout.size.bytes_usize()];
    let mut write = |offset: Size, scalar: interpret::Scalar| {
        match scalar {
            interpret::Scalar::Int(int) => {
                let mut scalar = vec![0; int.size().bytes_usize()];
                let endian = s.base().tcx.data_layout.endian;
                interpret::write_target_uint(endian, &mut scalar, int.to_bits(int.size())).unwrap();
                for (i, b) in scalar.into_iter().enumerate() {
                    bytes[offset.bytes_usize() + i] = ConstantByte::Value(b);
                }
            }
            interpret::Scalar::Ptr(ptr, size) => {
                let (prov, ptr_offset) = ptr.into_raw_parts();
                let prov = alloc_provenance(s, prov.alloc_id());
                let ptr_offset =
                    Size::from_bytes(size.get()).sign_extend(ptr_offset.bytes().into());
                for i in 0..size.get() {
                    bytes[offset.bytes_usize() + i as usize] =
                        ConstantByte::Provenance(prov.clone(), ptr_offset as i64, i);
                }
            }
        };
    };
    match **imm {
        Immediate::Uninit => {}
        Immediate::Scalar(a) => write(Size::ZERO, a),
        Immediate::ScalarPair(a, b) => {
            let rustc_abi::BackendRepr::ScalarPair { b_offset, .. } = imm.layout.backend_repr
            else {
                unreachable!()
            };
            write(Size::ZERO, a);
            write(b_offset, b);
        }
    }
    bytes
}

/// The bytes of a value in memory.
fn mplace_to_raw_bytes<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    mplace: &rustc_const_eval::interpret::MPlaceTy<'tcx>,
) -> InterpResult<'tcx, Vec<ConstantByte>> {
    use rustc_abi::Size;
    let size = mplace.layout.size;
    if size.bytes() == 0 {
        return interp_ok(vec![]);
    }
    let (alloc_id, offset, _) = ecx.ptr_get_alloc_id(mplace.ptr(), size.bytes() as i64)?;
    let alloc = ecx.get_alloc_raw(alloc_id)?;
    let range = interpret::alloc_range(offset, size);
    let raw_bytes = alloc.get_bytes_unchecked(range);
    let mut bytes: Vec<ConstantByte> = (0..size.bytes())
        .map(
            |i| match alloc.init_mask().get(offset + Size::from_bytes(i)) {
                true => ConstantByte::Value(raw_bytes[i as usize]),
                false => ConstantByte::Uninit,
            },
        )
        .collect();

    // The bytes of a pointer hold its offset into its target.
    let data_layout = &s.base().tcx.data_layout;
    let (ptr_size, endian) = (data_layout.pointer_size(), data_layout.endian);
    let read_offset =
        |raw: &[u8]| ptr_size.sign_extend(interpret::read_target_uint(endian, raw).unwrap()) as i64;
    // Whole pointers, including the ones that only partially overlap with the range.
    let first = range.start - Size::from_bytes(range.start.bytes().min(ptr_size.bytes() - 1));
    for &(start, prov) in alloc.provenance().ptrs().range(first..range.end()) {
        let target = alloc_provenance(s, prov.alloc_id());
        let offset =
            read_offset(alloc.get_bytes_unchecked(interpret::alloc_range(start, ptr_size)));
        for i in 0..ptr_size.bytes() {
            let pos = start + Size::from_bytes(i);
            if range.start <= pos && pos < range.end() {
                bytes[(pos - range.start).bytes_usize()] =
                    ConstantByte::Provenance(target.clone(), offset, i as u8);
            }
        }
    }
    // Fragments of pointers.
    for (i, byte) in bytes.iter_mut().enumerate() {
        if !matches!(byte, ConstantByte::Provenance(..))
            && let Some(frag) = alloc
                .provenance()
                .get_byte(range.start + Size::from_bytes(i), ecx)
        {
            let target = alloc_provenance(s, frag.prov.alloc_id());
            let offset = read_offset(&frag.bytes[..ptr_size.bytes_usize()]);
            *byte = ConstantByte::Provenance(target, offset, frag.idx);
        }
    }
    interp_ok(bytes)
}

/// The concrete type behind the `dyn` tail of `place`, found in its vtable.
fn dyn_concrete_ty<'tcx>(
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    place: &rustc_const_eval::interpret::MPlaceTy<'tcx>,
    preds: &'tcx ty::List<ty::PolyExistentialPredicate<'tcx>>,
) -> InterpResult<'tcx, ty::Ty<'tcx>> {
    use rustc_const_eval::interpret::Projectable;
    let vtable = place.meta().unwrap_meta().to_pointer(ecx);
    ecx.get_ptr_vtable_ty(vtable, Some(preds))
}

/// The metadata of a pointer to `place`, whose type is unsized.
fn pointer_metadata<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    place: &rustc_const_eval::interpret::MPlaceTy<'tcx>,
) -> InterpResult<'tcx, UnsizingMetadata> {
    use rustc_const_eval::interpret::Projectable;
    let tcx = s.base().tcx;
    let tail = tcx.struct_tail_for_codegen(place.layout.ty, s.typing_env());
    // The sized type the tail would be unsized from.
    let sized_tail = match tail.kind() {
        ty::Slice(_) | ty::Str => {
            let len = place.meta().unwrap_meta().to_target_usize(ecx)?;
            ty::Ty::new_array(tcx, tail.sequence_element_type(tcx), len)
        }
        ty::Dynamic(preds, ..) => dyn_concrete_ty(ecx, place, preds)?,
        _ => unreachable!("unexpected unsized tail type {tail:?}"),
    };
    let sized_tail = ty::Ty::new_imm_ref(tcx, tcx.lifetimes.re_static, sized_tail);
    let unsized_tail = ty::Ty::new_imm_ref(tcx, tcx.lifetimes.re_static, tail);
    interp_ok(compute_unsizing_metadata(s, sized_tail, unsized_tail))
}

/// The projection to the place located `offset` bytes after the current place, for a pointee of type `ty`.
fn offset_projection<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    offset: rustc_abi::Size,
    ty: ty::Ty<'tcx>,
    size: rustc_abi::Size,
) -> Vec<ConstantProjectionElem> {
    let (offset, size) = (offset.bytes(), size.bytes());
    if offset == 0 {
        return vec![];
    }
    let (count, ty) = if offset.is_multiple_of(size) {
        (offset / size, Some(ty.sinto(s)))
    } else {
        (offset, None)
    };
    vec![ConstantProjectionElem::Offset { count, ty }]
}

/// Find the subplace of `place` that contains the place of type `to_ty` and size `size` located
/// `offset` bytes after `place`. Returns the projection to that subplace, the subplace, and the
/// offset of the target within it.
fn find_subplace<'tcx>(
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    place: &rustc_const_eval::interpret::MPlaceTy<'tcx>,
    offset: rustc_abi::Size,
    to_ty: ty::Ty<'tcx>,
    size: rustc_abi::Size,
) -> InterpResult<
    'tcx,
    Option<(
        ConstantProjectionElem,
        rustc_const_eval::interpret::MPlaceTy<'tcx>,
        rustc_abi::Size,
    )>,
> {
    use rustc_const_eval::interpret::Projectable;
    match place.layout.ty.kind() {
        ty::Array(elem, _) => {
            let len = place.len(ecx)?;
            let stride = place.layout.field(ecx, 0).size.bytes();
            let Some(i) = offset.bytes().checked_div(stride) else {
                return interp_ok(None);
            };
            // The target may be a subarray.
            if let ty::Array(target_elem, _) = to_ty.kind()
                && target_elem == elem
                && offset.bytes().is_multiple_of(stride)
                && i + size.bytes() / stride <= len
            {
                let (from, to) = (i, i + size.bytes() / stride);
                let subslice = mir::ProjectionElem::Subslice {
                    from,
                    to,
                    from_end: false,
                };
                let sub = ecx.project(place, subslice)?;
                let proj = ConstantProjectionElem::Subslice { from, to };
                return interp_ok(Some((proj, sub, rustc_abi::Size::ZERO)));
            }
            // The element that contains the target, if any.
            if i < len && offset.bytes() + size.bytes() <= (i + 1) * stride {
                let sub_offset = offset - rustc_abi::Size::from_bytes(i * stride);
                let proj = ConstantProjectionElem::Index(i);
                return interp_ok(Some((proj, ecx.project_index(place, i)?, sub_offset)));
            }
        }
        ty::Adt(..) | ty::Tuple(..) | ty::Closure(..) => {
            let (place, variant) = match place.layout.ty.kind() {
                ty::Adt(adt_def, _) if adt_def.is_enum() => {
                    let variant = ecx.read_discriminant(place)?;
                    (ecx.project_downcast(place, variant)?, Some(variant))
                }
                _ => (place.clone(), None),
            };
            // The field that contains the target, if any.
            for i in 0..place.layout.fields.count() {
                let field_offset = place.layout.fields.offset(i);
                let field_size = place.layout.field(ecx, i).size;
                if field_offset <= offset && offset + size <= field_offset + field_size {
                    let field = FieldIdx::from_usize(i);
                    let proj = ConstantProjectionElem::Field(variant, field);
                    let sub = ecx.project_field(&place, field)?;
                    return interp_ok(Some((proj, sub, offset - field_offset)));
                }
            }
        }
        _ => {}
    }
    interp_ok(None)
}

/// Find projections from `place` to the place of type `to_ty` located `offset` bytes after it.
/// There may be many ways of reaching the same destination. Returns the projections to use,
/// and the type of the final place, which may not match `to_ty`, in which case a cast is needed.
fn structural_path<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    mut place: rustc_const_eval::interpret::MPlaceTy<'tcx>,
    mut offset: rustc_abi::Size,
    to_ty: ty::Ty<'tcx>,
    size: rustc_abi::Size,
) -> (Vec<ConstantProjectionElem>, ty::Ty<'tcx>) {
    let mut path = vec![];
    while !(place.layout.ty == to_ty && offset == rustc_abi::Size::ZERO) {
        match find_subplace(ecx, &place, offset, to_ty, size).discard_err() {
            Some(Some((proj, sub, sub_offset))) => {
                path.push(proj);
                place = sub;
                offset = sub_offset;
            }
            _ => {
                // Give up: we couldn't find a typed path, so we offset from the place we reached.
                path.extend(offset_projection(s, offset, to_ty, size));
                return (path, place.layout.ty);
            }
        }
    }
    (path, to_ty)
}

/// Express a place of type `ty` located `offset` bytes into the allocation as projections from
/// the global `item` that stands for the allocation. Returns the type of the global, the
/// projections and the type of the place they reach, which is `ty` unless the pointer must be
/// cast.
fn place_in_alloc<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    place: &rustc_const_eval::interpret::MPlaceTy<'tcx>,
    alloc_id: interpret::AllocId,
    item: &ItemRef,
    offset: rustc_abi::Size,
    ty: ty::Ty<'tcx>,
) -> Option<(ty::Ty<'tcx>, Vec<ConstantProjectionElem>, ty::Ty<'tcx>)> {
    let tcx = s.base().tcx;
    let layout_of = |ty| tcx.layout_of(s.typing_env().as_query_input(ty)).ok();
    let ty = tcx.erase_and_anonymize_regions(ty);
    let size = layout_of(ty)?.size;
    let decl_ty = normalize(
        tcx,
        s.typing_env(),
        item.def_id.type_of(s).instantiate_identity(),
    );
    let decl_ty = tcx.erase_and_anonymize_regions(decl_ty);
    // Anonymous allocations are untyped (their global is a `MaybeUninit<[u8; N]>`), so we only
    // follow the structure of statics.
    let (path, end_ty) = if let interpret::GlobalAlloc::Static(_) = tcx.global_alloc(alloc_id) {
        let (prov, _) = place.ptr().into_raw_parts();
        let ptr = interpret::Pointer::new(prov, rustc_abi::Size::ZERO);
        let base = ecx.ptr_to_mplace(ptr, layout_of(decl_ty)?);
        structural_path(s, ecx, base, offset, ty, size)
    } else {
        (offset_projection(s, offset, ty, size), decl_ty)
    };
    Some((decl_ty, path, end_ty))
}

/// The sized type at which to view the pointee `place`. A slice or `dyn Trait` value is viewed at
/// the sized type it was unsized from, and so is a `str` with `--unsized-strings`. Other unsized
/// values (e.g. a `CStr`) have no such type.
fn sized_view<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    place: &rustc_const_eval::interpret::MPlaceTy<'tcx>,
) -> InterpResult<'tcx, Option<ty::Ty<'tcx>>> {
    use rustc_const_eval::interpret::Projectable;
    let tcx = s.base().tcx;
    let ty = place.layout.ty;
    interp_ok(match ty.kind() {
        ty::Slice(elem) => Some(ty::Ty::new_array(tcx, *elem, place.len(ecx)?)),
        ty::Str if s.base().options.unsized_strings => {
            Some(ty::Ty::new_array(tcx, tcx.types.u8, place.len(ecx)?))
        }
        ty::Dynamic(preds, ..) => Some(dyn_concrete_ty(ecx, place, preds)?),
        _ if ty.is_sized(tcx, s.typing_env()) => Some(ty),
        _ => None,
    })
}

/// Convert a valid pointer of type `ptr_ty`. Pointers to globals are kept as pointers into these
/// globals, and we fallback to reading the bytes of the pointee for other cases.
fn pointer_to_const<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    span: rustc_span::Span,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    place: rustc_const_eval::interpret::MPlaceTy<'tcx>,
    ptr_ty: ty::Ty<'tcx>,
) -> InterpResult<'tcx, ConstantExprKind> {
    use rustc_const_eval::interpret::Projectable;
    let tcx = s.base().tcx;
    let ty = place.layout.ty;
    let (ty::Ref(.., mutability) | ty::RawPtr(_, mutability)) = *ptr_ty.kind() else {
        unreachable!()
    };
    let ptr_kind = |arg, projections, metadata| match ptr_ty.kind() {
        ty::Ref(..) => ConstantExprKind::Borrow(arg, projections, metadata),
        _ => ConstantExprKind::RawBorrow {
            mutability: mutability.sinto(s),
            arg,
            projections,
            metadata,
        },
    };

    let metadata = if ty.is_sized(tcx, s.typing_env()) {
        None
    } else {
        Some(pointer_metadata(s, ecx, &place)?)
    };
    let global_ty = sized_view(s, ecx, &place)?;

    let (alloc_id, offset, _) = ecx.ptr_get_alloc_id(place.ptr(), 0)?;
    if let Some(global_ty) = global_ty
        && let Some(item) = alloc_as_global(s, alloc_id)
        && let Some((decl_ty, projections, end_ty)) =
            place_in_alloc(s, ecx, &place, alloc_id, &item, offset, global_ty)
    {
        let base = ConstantExprKind::NamedGlobal(item).decorate(decl_ty.sinto(s), span.sinto(s));
        if end_ty == tcx.erase_and_anonymize_regions(global_ty) {
            interp_ok(ptr_kind(base, projections, metadata))
        } else {
            // Point to the place we reached, then cast the pointer to the right type.
            let inner = ConstantExprKind::RawBorrow {
                mutability: mutability.sinto(s),
                arg: base,
                projections,
                metadata: None,
            };
            let inner_ty = ty::Ty::new_ptr(tcx, end_ty, mutability);
            let inner = inner.decorate(inner_ty.sinto(s), span.sinto(s));
            if metadata.is_none() {
                interp_ok(ConstantExprKind::PtrCast(inner, None))
            } else {
                // Cast to the sized type first, then unsize.
                let sized_ty = ty::Ty::new_ptr(tcx, global_ty, mutability);
                let sized = ConstantExprKind::PtrCast(inner, None);
                let sized = sized.decorate(sized_ty.sinto(s), span.sinto(s));
                interp_ok(ConstantExprKind::PtrCast(sized, metadata))
            }
        }
    } else {
        // HACK: fallback to reading the bytes of the pointee, at the type of `global_ty`.
        let place = match global_ty {
            Some(global_ty) if global_ty != ty => {
                let layout = tcx
                    .layout_of(s.typing_env().as_query_input(global_ty))
                    .unwrap();
                // retype the place
                place.offset(rustc_abi::Size::ZERO, layout, ecx)?
            }
            _ => place,
        };
        let val = op_to_const(s, span, ecx, place.into())?;
        interp_ok(ptr_kind(val, vec![], metadata))
    }
}

/// Use the const-eval interpreter to convert an evaluated operand back to a structured
/// constant expression.
fn op_to_const<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    span: rustc_span::Span,
    ecx: &const_eval::CompileTimeInterpCx<'tcx>,
    op: rustc_const_eval::interpret::OpTy<'tcx>,
) -> InterpResult<'tcx, ConstantExpr> {
    use rustc_const_eval::interpret::Projectable;
    // Code inspired from `try_destructure_mir_constant_for_user_output` and
    // `const_eval::eval_queries::op_to_const`.
    let ty = op.layout.ty;
    // Helper for struct-likes.
    let read_fields = |of: rustc_const_eval::interpret::OpTy<'tcx>, field_count| {
        (0..field_count).map(move |i| {
            let field_op = ecx.project_field(&of, rustc_abi::FieldIdx::from_usize(i))?;
            op_to_const(s, span, ecx, field_op)
        })
    };
    let kind = match ty.kind() {
        ty::Char | ty::Bool | ty::Uint(_) | ty::Int(_) | ty::Float(_) => {
            let scalar = ecx.read_scalar(&op)?;
            let scalar_int = scalar.try_to_scalar_int().unwrap();
            let lit = scalar_int_to_constant_literal(s, scalar_int, ty);
            ConstantExprKind::Literal(lit)
        }
        ty::Adt(adt_def, ..) if adt_def.is_union() => {
            ConstantExprKind::Memory(op_to_raw_bytes(s, ecx, &op)?)
        }
        ty::Adt(adt_def, ..) => {
            let variant = ecx.read_discriminant(&op)?;
            let op = if adt_def.is_enum() {
                ecx.project_downcast(&op, variant)?
            } else {
                op
            };
            let field_count = adt_def.variants()[variant].fields.len();
            let fields = read_fields(op, field_count)
                .zip(&adt_def.variant(variant).fields)
                .map(|(value, field)| {
                    interp_ok(ConstantFieldExpr {
                        field: field.did.sinto(s),
                        value: value?,
                    })
                })
                .collect::<InterpResult<Vec<_>>>()?;
            ConstantExprKind::Adt {
                kind: get_variant_kind(adt_def, variant, s),
                fields,
            }
        }
        ty::Closure(def_id, args) => {
            // A closure is essentially an adt with funky generics and some builtin impls.
            let def_id: DefId = def_id.sinto(s);
            let field_count = args.as_closure().upvar_tys().len();
            let fields = read_fields(op, field_count)
                .map(|value| {
                    interp_ok(ConstantFieldExpr {
                        // HACK: Closure fields don't have their own def_id, but Charon doesn't use
                        // field DefIds so we put a dummy one.
                        field: def_id.clone(),
                        value: value?,
                    })
                })
                .collect::<InterpResult<Vec<_>>>()?;
            ConstantExprKind::Adt {
                kind: VariantKind::Struct,
                fields,
            }
        }
        ty::Tuple(args) => {
            let fields = read_fields(op, args.len()).collect::<InterpResult<Vec<_>>>()?;
            ConstantExprKind::Tuple { fields }
        }
        ty::Array(..) | ty::Slice(..) => {
            let len = op.len(ecx)?;
            let fields = (0..len)
                .map(|i| {
                    let op = ecx.project_index(&op, i)?;
                    op_to_const(s, span, ecx, op)
                })
                .collect::<InterpResult<Vec<_>>>()?;
            ConstantExprKind::Array { fields }
        }
        ty::Str => {
            let str = ecx.read_str(&op.assert_mem_place())?;
            ConstantExprKind::Literal(ConstantLiteral::Str(str.to_owned()))
        }
        ty::FnDef(def_id, args) => {
            let args = args.no_bound_vars().expect("bound variables in FnDef");
            let item = translate_item_ref(s, *def_id, args);
            ConstantExprKind::FnDef(item)
        }
        ty::FnPtr(..) => {
            let fn_ptr = ecx.read_pointer(&op)?;
            let (alloc_id, ..) = ecx.ptr_get_alloc_id(fn_ptr, 0)?;
            match alloc_provenance(s, alloc_id) {
                ConstantByteProvenance::Function(item) => ConstantExprKind::FnPtr(item),
                ConstantByteProvenance::ClosureAsFn(closure) => {
                    ConstantExprKind::ClosureAsFn(closure)
                }
                _ => ConstantExprKind::Todo("Unexpected function pointer".into()),
            }
        }
        ty::RawPtr(_, mutability) | ty::Ref(_, _, mutability) => {
            let place = ecx.deref_pointer(&op)?;
            // Make sure we only read through if it's not dangling!
            if ecx.ptr_get_alloc_id(place.ptr(), 0).discard_err().is_some() {
                pointer_to_const(s, span, ecx, place, ty)?
            } else if let (None, addr) = place.ptr().into_raw_parts() {
                // A pointer without provenance, e.g. null or the pointer of an empty slice.
                let lit = ConstantExprKind::Literal(ConstantLiteral::PtrNoProvenance(
                    addr.bytes().into(),
                ));
                if place.layout.is_sized() {
                    lit
                } else if let Some(sized_ty) = sized_view(s, ecx, &place)? {
                    // Unsize the thin pointer with the metadata.
                    let thin_ty = ty::Ty::new_ptr(s.base().tcx, sized_ty, *mutability);
                    let thin = lit.decorate(thin_ty.sinto(s), span.sinto(s));
                    let metadata = pointer_metadata(s, ecx, &place)?;
                    ConstantExprKind::PtrCast(thin, Some(metadata))
                } else {
                    ConstantExprKind::Todo("dangling pointer to an unsized value".into())
                }
            } else {
                ConstantExprKind::Todo("dangling pointer".into())
            }
        }
        ty::Pat(..) => {
            let op = ecx.project_field(&op, FieldIdx::from_u16(0))?;
            *op_to_const(s, span, ecx, op)?.contents
        }
        ty::Dynamic(preds, ..) => {
            let place = op.assert_mem_place();
            let concrete_ty = dyn_concrete_ty(ecx, &place, preds)?;
            let layout = (s.base().tcx)
                .layout_of(s.typing_env().as_query_input(concrete_ty))
                .unwrap();
            let place = place.offset(rustc_abi::Size::ZERO, layout, ecx)?;
            return op_to_const(s, span, ecx, place.into());
        }
        ty::Foreign(..)
        | ty::UnsafeBinder(..)
        | ty::CoroutineClosure(..)
        | ty::Coroutine(..)
        | ty::CoroutineWitness(..) => ConstantExprKind::Todo("Unhandled constant type".into()),
        ty::Alias(..) | ty::Param(..) | ty::Bound(..) | ty::Placeholder(..) | ty::Infer(..) => {
            fatal!(s[span], "Encountered evaluated constant of non-monomorphic type"; {op})
        }
        ty::Never | ty::Error(..) => {
            fatal!(s[span], "Encountered evaluated constant of invalid type"; {ty})
        }
    };
    let val = kind.decorate(ty.sinto(s), span.sinto(s));
    interp_ok(val)
}

pub fn const_value_to_constant_expr<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ty: rustc_middle::ty::Ty<'tcx>,
    val: mir::ConstValue,
    span: rustc_span::Span,
) -> InterpResult<'tcx, ConstantExpr> {
    let tcx = s.base().tcx;
    let typing_env = s.typing_env();
    let (ecx, op) =
        const_eval::mk_eval_cx_for_const_val(tcx.at(span), typing_env, val, ty).unwrap();
    op_to_const(s, span, &ecx, op)
}

/// Like `const_value_to_constant_expr`, but untyped.
pub fn const_value_to_raw_memory<'tcx, S: UnderOwnerState<'tcx>>(
    s: &S,
    ty: rustc_middle::ty::Ty<'tcx>,
    val: mir::ConstValue,
    span: rustc_span::Span,
) -> InterpResult<'tcx, ConstantExpr> {
    let tcx = s.base().tcx;
    let (ecx, op) =
        const_eval::mk_eval_cx_for_const_val(tcx.at(span), s.typing_env(), val, ty).unwrap();
    let bytes = op_to_raw_bytes(s, &ecx, &op)?;
    interp_ok(ConstantExprKind::Memory(bytes).decorate(ty.sinto(s), span.sinto(s)))
}
